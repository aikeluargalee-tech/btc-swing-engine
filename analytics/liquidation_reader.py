"""Liquidation Detector Telemetry Reader & Integrator.

Safely reads, caches, and parses `latest_detector_report.json` generated by
the companion `btc_liquidation_detector` engine (running independently in
`C:\\Users\\aikel\\.gemini\\antigravity\\scratch\\btc_liquidation_detector`).

Guarantees:
- Non-blocking, zero network I/O in the 2 Hz HUD loop.
- In-memory mtime cache prevents disk thrashing.
- Graceful degradation: returns safe fallback report if detector is offline,
  stale, or temporarily locked during atomic write.
"""

import json
import logging
import os
import time
from pathlib import Path
from typing import Optional

from core.models import (
    LiquidationDetectorReport,
    LiquidationWindow,
    PostFlushStructure,
)

logger = logging.getLogger(__name__)

# Module-level cache to ensure sub-millisecond lookups during high-frequency HUD renders
_CACHED_REPORT: Optional[LiquidationDetectorReport] = None
_CACHED_MTIME: float = 0.0
_LAST_CHECK_TS: float = 0.0
_CHECK_INTERVAL_SEC: float = 1.0  # Check disk mtime at most once per second


def read_latest_liquidation_report(
    report_path: Optional[os.PathLike] = None,
    stale_threshold_sec: float = 1800.0,  # 30 minutes
) -> LiquidationDetectorReport:
    """Reads and parses the latest liquidation detector report safely.

    Returns a LiquidationDetectorReport with `is_available=True` if valid data
    was read, or `is_available=False` if missing, locked, or unreadable.
    """
    global _CACHED_REPORT, _CACHED_MTIME, _LAST_CHECK_TS

    now = time.time()
    if report_path is None:
        env_path = os.environ.get(
            "LIQUIDATION_REPORT_PATH",
            r"C:\Users\aikel\.gemini\antigravity\scratch\btc_liquidation_detector\latest_detector_report.json",
        )
        report_path = Path(env_path)
    else:
        report_path = Path(report_path)

    # Return cached if checked very recently
    if _CACHED_REPORT is not None and (now - _LAST_CHECK_TS) < _CHECK_INTERVAL_SEC:
        return _CACHED_REPORT

    _LAST_CHECK_TS = now

    if not report_path.is_file():
        # Detector not running or file path not yet created
        if _CACHED_REPORT is not None:
            return _CACHED_REPORT
        return LiquidationDetectorReport(
            verdict="DETECTOR OFFLINE",
            verdict_detail="Companion btc_liquidation_detector feed not detected or file missing.",
            is_available=False,
            is_stale=True,
            source_file=str(report_path),
        )

    try:
        mtime = os.path.getmtime(report_path)
        if _CACHED_REPORT is not None and mtime == _CACHED_MTIME:
            return _CACHED_REPORT

        # Read file with UTF-8
        with open(report_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        ts_ms = int(data.get("timestamp_ms") or 0)
        ts_utc = str(data.get("timestamp_utc") or "")
        age_sec = (now * 1000 - ts_ms) / 1000.0 if ts_ms > 0 else 0.0
        is_stale = age_sec > stale_threshold_sec

        # Parse windows
        windows_dict = {}
        raw_windows = data.get("windows") or {}
        for w_key in ("15m", "1h", "4h", "24h"):
            w_data = raw_windows.get(w_key) or {}
            windows_dict[w_key] = LiquidationWindow(
                long_usd=float(w_data.get("long_usd") or 0.0),
                short_usd=float(w_data.get("short_usd") or 0.0),
                total_usd=float(w_data.get("total_usd") or 0.0),
                long_count=int(w_data.get("long_count") or 0),
                short_count=int(w_data.get("short_count") or 0),
                dominant_side=str(w_data.get("dominant_side") or "NEUTRAL"),
            )

        # Parse post-flush structure
        raw_struct = data.get("post_flush_price_structure") or {}
        details = raw_struct.get("details") or {}
        post_struct = PostFlushStructure(
            status=str(raw_struct.get("status") or "NONE"),
            stabilisation_confirmed=bool(raw_struct.get("stabilisation_confirmed")),
            stopped_making_lower_lows=bool(raw_struct.get("stopped_making_lower_lows")),
            higher_low_formed=bool(raw_struct.get("higher_low_formed")),
            break_prior_structure_high=bool(raw_struct.get("break_prior_structure_high")),
            spot_volume_expanded=bool(raw_struct.get("spot_volume_expanded")),
            volume_ratio=float(details.get("volume_ratio") or 1.0),
        )

        # Parse market context
        raw_ctx = data.get("market_context") or {}
        oi_contracts = float(raw_ctx.get("open_interest_contracts") or 0.0)
        fund_rate = float(raw_ctx.get("funding_rate") or 0.0)
        fund_status = str(raw_ctx.get("funding_status") or "")

        # Parse demand zone
        raw_dz = data.get("demand_zone_analysis") or {}
        dz_status = str(raw_dz.get("status") or "N/A")
        dz_lower = float(raw_dz.get("lower_boundary") or 0.0)
        dz_upper = float(raw_dz.get("upper_boundary") or 0.0)
        dz_dist_lower = float(raw_dz.get("distance_to_lower_pct") or 0.0)
        dz_dist_upper = float(raw_dz.get("distance_to_upper_pct") or 0.0)

        report = LiquidationDetectorReport(
            timestamp_utc=ts_utc,
            timestamp_ms=ts_ms,
            verdict=str(data.get("verdict") or "NORMAL"),
            verdict_detail=str(data.get("verdict_detail") or ""),
            primary_classification=str(data.get("primary_classification") or "NORMAL"),
            magnitude_tier=str(data.get("magnitude_tier") or "NORMAL"),
            liquidation_multiple_24h=float(data.get("liquidation_multiple_24h") or 0.0),
            directional_classification=str(data.get("directional_classification") or "NEUTRAL"),
            windows=windows_dict,
            post_flush_price_structure=post_struct,
            is_stale=is_stale,
            is_available=True,
            source_file=str(report_path),
            demand_zone_status=dz_status,
            demand_zone_lower=dz_lower,
            demand_zone_upper=dz_upper,
            demand_zone_dist_lower_pct=dz_dist_lower,
            demand_zone_dist_upper_pct=dz_dist_upper,
            open_interest_contracts=oi_contracts,
            funding_rate=fund_rate,
            funding_status=fund_status,
        )

        _CACHED_REPORT = report
        _CACHED_MTIME = mtime
        return report

    except (json.JSONDecodeError, PermissionError, OSError) as exc:
        logger.debug("Non-fatal liquidation report read glitch: %s", exc)
        if _CACHED_REPORT is not None:
            return _CACHED_REPORT
        return LiquidationDetectorReport(
            verdict="FEED READ GLITCH",
            verdict_detail=f"Transient read error: {type(exc).__name__}",
            is_available=False,
            is_stale=True,
            source_file=str(report_path),
        )


def reset_liquidation_cache() -> None:
    """Clears cached report for deterministic testing."""
    global _CACHED_REPORT, _CACHED_MTIME, _LAST_CHECK_TS
    _CACHED_REPORT = None
    _CACHED_MTIME = 0.0
    _LAST_CHECK_TS = 0.0
